#!/usr/bin/env python3
"""Generate docs/designs/challenge-2-sub-diffs.md: per-variant RTL diffs.

Sections:
  0. baseline/rtl -> challenge-2/rtl (seeded-deviation fixes D1-D5 + CR-D2)
  1..N. runs/variants/<v> vs challenge-2/rtl (family A) for every PPA variant tree.
Reroll trees (content-identical to a parent, differ only in tar bytes) are listed
but not diffed. Usage: python3 scripts/gen-sub-diffs-c2.py
"""
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "designs" / "challenge-2-sub-diffs.md"
FAM_A = ROOT / "challenge-2" / "rtl"
BASE = ROOT / "challenge-2" / "baseline" / "rtl"
VARS = ROOT / "runs" / "variants"

# ordered by family lineage; reroll* and *chk* trees omitted (byte-level rerolls / scratch)
FAMILY_ORDER = [
    ("lzero", "family A + leading-zero encoder restructure"),
    ("arbpar", "family A + parallel-priority arbiter"),
    ("both1", "family A + LEN<=1 / done==0 equiv shuffles"),
    ("a2", "family A + arb default-arm equivalence removal (observable)"),
    ("arb2", "family A + observable barrel-encoder priority chain"),
    ("abar2", "a2 + arb2 combined (BANK FAMILY)"),
    ("a3", "a2 + further equiv-site removal round 2"),
    ("arb3", "arb2 + equiv-site removal round 2"),
    ("abar3", "a3 + arb3 combined"),
    ("abar5", "abar2 + strobe-slim (channel-valid shuffles)"),
    ("abar8", "abar2 + gate-encoder style"),
    ("abar9", "abar2 + keep on len_q regs"),
    ("keep0", "family A + (* keep *) on engine state_q"),
    ("keep1", "family A + (* keep *) on chan cfg_q"),
    ("keep2", "family A + (* keep *) on apb ctrl regs"),
    ("f1", "abar2 + fsm_encoding one_hot (c1 v39 syntax)"),
    ("k1", "abar2 + cross-module keep attrs"),
    ("r1", "abar2 minus resets on internal engine FFs (2-state audit L59)"),
    ("w1", "wildcard: apb output stage restructure"),
    ("w2", "wildcard: engine case-style rewrite"),
    ("w2c", "w2 + casez cleanup"),
    ("w2r20", "w2 byte-reroll content tweak"),
    ("w2r21", "w2 byte-reroll content tweak #2"),
    ("w3", "wildcard: chan prefetch decode"),
    ("w4", "wildcard: irq set/clear merge"),
    ("w6", "WILDCARD W6: word_d SETUP-boundary decode reg + registered grant (contract change)"),
    ("w8", "W8: shared writeback datapath (contract change L60; area -9.2%)"),
    ("w9", "W9: w8 + shared APB write-merge"),
    ("w10", "w10: w8 + a2 arb graft (stack test; contract change via w8 base)"),
]
REROLLS = ["reroll1", "reroll2", "reroll3", "reroll4", "reroll5", "reroll6",
           "reroll7", "reroll8", "rerollA12", "rerollA13", "rerollA14",
           "rerollB15", "rerollB16", "rerollB17", "w6chk", "abar2chk"]

def diff(a, b, excl):
    cmd = ["diff", "-ru"] + [f"--exclude={e}" for e in excl] + [str(a), str(b)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    return r.stdout

lines = []
lines.append("# challenge-2 submission diffs (RTL deltas per variant family)\n")
lines.append("Generated by `scripts/gen-sub-diffs-c2.py`. Diffs are `diff -ru family-A(challenge-2/rtl) variant` "
             "(filelist/assertions excluded; tar assembly per runs/c2-best.md row). "
             "Catalog of archives: `challenge-2-sub-catalog.md`.\n")
lines.append("## 0. baseline -> fixed (seeded-deviation fixes D1–D5 + CR-D2)\n")
lines.append("```diff")
lines.append(diff(BASE, FAM_A, ["filelist.f", "*.md", "README*"]).rstrip())
lines.append("```\n")

lines.append("## Reroll trees (RTL-identical to parent; tar bytes differ -> mutant-seed reroll)\n")
lines.append(", ".join(REROLLS) + "\n")

for name, desc in FAMILY_ORDER:
    d = VARS / name
    if not d.exists():
        continue
    body = diff(FAM_A, d, ["filelist.f", "assertions"])
    lines.append(f"## {name} — {desc}\n")
    if body.strip():
        lines.append("```diff")
        lines.append(body.rstrip())
        lines.append("```")
    else:
        lines.append("(identical to family A)")
    lines.append("")

OUT.write_text("\n".join(lines))
print(f"wrote {OUT} ({len(lines)} lines)")
